export const RECIPIENTS_STORAGE_KEY = 'flowpulse_campaign_recipients';

export function loadAllStoredRecipients(fallback: CampaignRecipient[] = ENTERPRISE_SAMPLE_PACK.slice(0, 12)): CampaignRecipient[] {
  try {
    const raw = localStorage.getItem(RECIPIENTS_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) return parsed;
    }
  } catch (e) {
    // ignore
  }
  return fallback;
}

export function saveAllRecipients(recipients: CampaignRecipient[]): void {
  try {
    localStorage.setItem(RECIPIENTS_STORAGE_KEY, JSON.stringify(recipients));
    // Dispatch custom window event so all open components sync immediately
    window.dispatchEvent(new CustomEvent('flowpulse_recipients_updated', { detail: recipients }));
  } catch (e) {
    // ignore
  }
}

export function appendRecipientsToStorage(newRecipients: CampaignRecipient[]): CampaignRecipient[] {
  const current = loadAllStoredRecipients();
  const existingPhones = new Set(current.map((c) => c.phone.replace(/\s+/g, '')));
  
  const uniqueNew = newRecipients.filter(
    (item) => !existingPhones.has(item.phone.replace(/\s+/g, ''))
  );

  const updated = [...uniqueNew, ...current];
  saveAllRecipients(updated);
  return updated;
}

