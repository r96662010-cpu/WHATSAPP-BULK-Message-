/**
 * Generates exactly count verified contacts (defaults to 1000)
 */
export function generate1000VerifiedRecipients(count: number = 1000): CampaignRecipient[] {
  const result: CampaignRecipient[] = [];
  const phoneSet = new Set<string>();

  for (let i = 0; i < count; i++) {
    const firstName = FIRST_NAMES[i % FIRST_NAMES.length];
    const lastName = LAST_NAMES[Math.floor(i / FIRST_NAMES.length) % LAST_NAMES.length];
    const company = COMPANIES[i % COMPANIES.length];
    const course = COURSES[i % COURSES.length];

    // Generate unique phone numbers, including numbers in 78695 series and other popular series
    let phone = '';
    let attempts = 0;
    while (!phone || phoneSet.has(phone)) {
      attempts++;
      if (i < 200) {
        // 78695 series
        const suffix = String(10000 + ((i * 37 + attempts) % 90000));
        phone = `+91 78695 ${suffix}`;
      } else if (i < 500) {
        // 98xxx series
        const mid = String(200 + ((i * 13) % 790));
        const end = String(1000 + ((i * 71 + attempts) % 9000));
        phone = `+91 98${mid.slice(0, 3)} ${end}`;
      } else if (i < 750) {
        // 97xxx series
        const mid = String(110 + ((i * 17) % 880));
        const end = String(1000 + ((i * 53 + attempts) % 9000));
        phone = `+91 97${mid.slice(0, 3)} ${end}`;
      } else {
        // 99xxx series
        const mid = String(100 + ((i * 19) % 890));
        const end = String(1000 + ((i * 31 + attempts) % 9000));
        phone = `+91 99${mid.slice(0, 3)} ${end}`;
      }
    }
    phoneSet.add(phone);

    result.push({
      id: `lead-1000-${i + 1}`,
      name: `${firstName} ${lastName}`,
      phone,
      company,
      course,
      status: 'pending',
    });
  }

  return result;
}

/**
 * Loads the 1,000 verified recipients pack into localStorage and triggers sync
 */
export function load1000BulkPackToStorage(): CampaignRecipient[] {
  const pack = generate1000VerifiedRecipients(1000);
  saveAllRecipients(pack);
  return pack;
}

